"""Generate the example conversations in examples/*.md by running the real agent.

Requires NVIDIA_API_KEY (or a local NIM at NVIDIA_BASE_URL). Transcripts are
written exactly as produced by the model, including the tool calls, and are
never hand-edited. Usage: ``python scripts/run_examples.py``
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")

from emporio.agent import FALLBACK_MESSAGE, Agent  # noqa: E402
from emporio.history import HistoryStore  # noqa: E402
from emporio.tools import Tools  # noqa: E402

# (file slug, title, customer turns). Customers may write in Portuguese; Mel must answer in English.
SCENARIOS = [
    ("01_catalog_budget", "Catalog search within a budget",
     ["Quais opções de violões disponíveis custando até R$1000?"]),
    ("02_store_info", "Store address and opening hours", ["Qual o endereço da loja? E vocês abrem sábado?"]),
    ("03_price_pix_vs_promo", "Price, PIX discount and a promotional product (rule: no stacking)",
     ["Quanto custa o Takamine GD20?", "E o ukulele Ohana CK-20? Se eu pagar no PIX tenho desconto?"]),
    ("04_out_of_scope", "Out-of-scope and accessory requests",
     ["Vocês vendem cordas de violão?", "Qual a previsão do tempo amanhã em Campo Grande?"]),
    ("05_return_regret", "Non-trivial: privacy check + return policy applied to a real order",
     ["Me arrependi da minha compra, posso devolver meu pedido?",
      "É o pedido 7, meu e-mail é leticia.rocha@jmail.com"]),
]


def run(slug: str, title: str, turns: list[str], out_dir: Path) -> None:
    tools = Tools(sessions_dir=Path(tempfile.mkdtemp()))
    agent = Agent(tools=tools, history=HistoryStore(tempfile.mkdtemp()))
    lines = [f"# {title}", "", f"_Model: `{agent.model}`. Generated by `scripts/run_examples.py`; not edited by hand._", ""]
    for turn in turns:
        before = len(agent.history.load(slug))
        reply = agent.reply(slug, turn)
        if reply == FALLBACK_MESSAGE:
            raise SystemExit(f"{slug}: the model call failed (fallback message). Check key/base URL/model; "
                             "refusing to write a transcript from a failed run.")
        new_msgs = agent.history.load(slug)[before:]
        calls = [tc["function"] for m in new_msgs if m.get("tool_calls") for tc in m["tool_calls"]]
        lines += [f"**Customer:** {turn}", ""]
        if calls:
            lines += ["<details><summary>Tool calls in this turn</summary>", "", "```"]
            lines += [f"{c['name']}({c['arguments']})" for c in calls]
            lines += ["```", "</details>", ""]
        lines += [f"**Mel:** {reply}", ""]
    (out_dir / f"{slug}.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote examples/{slug}.md")


def main() -> int:
    import os
    hosted = "integrate.api.nvidia.com" in os.environ.get("NVIDIA_BASE_URL", "integrate.api.nvidia.com")
    if hosted and not os.environ.get("NVIDIA_API_KEY"):
        print("NVIDIA_API_KEY is not set. Set it in .env (or point NVIDIA_BASE_URL at a local NIM). "
              "Nothing was written.", file=sys.stderr)
        return 1
    out_dir = ROOT / "examples"
    out_dir.mkdir(exist_ok=True)
    for slug, title, turns in SCENARIOS:
        run(slug, title, turns, out_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
